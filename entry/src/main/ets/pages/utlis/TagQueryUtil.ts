export interface TagDataInterface {
  id: string
  enName: string
  zhName: string
}

/**
 * 标签查询工具类
 * 适配华为ArkTS，支持中文标签匹配id和英文名
 */
export class TagQueryUtil {
  // 初始化中文映射表（提升查询性能）
  private static zhTagMap: Map<string, { id: string; enName: string }> = new Map();

  static {
    // 预构建中文到id/英文名的映射
    TAG_DATA_SOURCE.forEach(item => {
      this.zhTagMap.set(item.zhName, { id: item.id, enName: item.enName });
      // 支持小写/大写模糊匹配（可选）
      this.zhTagMap.set(item.zhName.toLowerCase(), { id: item.id, enName: item.enName });
    });
  }

  /**
   * 根据中文标签查询对应的ID和英文名
   * @param zhName 中文标签名（如："科幻"、"冒险"）
   * @returns {id: string, enName: string} | null 匹配结果，无匹配返回null
   */
  static queryTagByZh(zhName: string): { id: string; enName: string } | null {
    if (!zhName || zhName.trim() === "") {
      console.warn("TagQueryUtil: 中文标签名不能为空");
      return null;
    }
    // 优先精确匹配，再尝试去空格/大小写匹配
    const targetZh = zhName.trim();
    let result = this.zhTagMap.get(targetZh);

    if (!result) {
      // 兼容处理：去除空格、全角半角转换
      const normalizedZh = targetZh.replace(/\s+/g, "").replace(/[\uff01-\uff5e]/g, char =>
      String.fromCharCode(char.charCodeAt(0) - 65248)
      );
      result = this.zhTagMap.get(normalizedZh) || null;
    }

    if (!result) {
      console.warn(`TagQueryUtil: 未找到匹配的标签 - ${zhName}`);
    }
    return result;
  }

  /**
   * 批量查询中文标签
   * @param zhNameList 中文标签列表（如：["科幻", "冒险", "喜剧"]）
   * @returns 匹配结果数组
   */
  static batchQueryTagsByZh(zhNameList: string[]): Array<{ zhName: string; id: string; enName: string } | null> {
    if (!Array.isArray(zhNameList) || zhNameList.length === 0) {
      console.warn("TagQueryUtil: 中文标签列表不能为空");
      return [];
    }
    return zhNameList.map(zhName => {
      const result = this.queryTagByZh(zhName);
      return result ? { zhName, ...result } : null;
    });
  }

  /**
   * 批量查询中文标签仅返回id
   * @param zhNameList 中文标签列表（如：["科幻", "冒险", "喜剧"]）
   * @returns 匹配结果id数组
   */
  static batchQueryTagsByZhGetIds(zhNameList: string[]): Array<string | null> {
    if (!Array.isArray(zhNameList) || zhNameList.length === 0) {
      console.warn("TagQueryUtil: 中文标签列表不能为空");
      return [];
    }
    return zhNameList.map(zhName => {
      const result = this.queryTagByZh(zhName);
      return result ? result.id : null;
    });
  }

  /**
   * 获取所有标签的中文-英文-ID对照表
   * @returns 完整标签列表
   */
  static getAllTags(): Array<{ id: string; enName: string; zhName: string }> {
    return [...TAG_DATA_SOURCE];
  }
}